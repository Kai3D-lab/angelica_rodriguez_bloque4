# First database operation - CRUD operation... 
# crear_producto(producto) receives a Producto object from the class
from app.database import conectar
from app.modelos import Producto

#----------------------
# CREATE - POST /items
# ---------------------
def crear_producto(producto):
    """Guarda un nuevo producto en la base de datos"""
    conexion = conectar()
    cursor = conexion.cursor()

# Insert the data from the Product object into the products table
    cursor.execute("""INSERT INTO productos (nombre, descripcion, 
        categoria, precio)
        VALUES (?, ?, ?, ?)""",
        (producto.nombre,
        producto.descripcion,
        producto.categoria,
        producto.precio))
    
# Save the changes in SQLite
    conexion.commit()
# Retrieve the ID automatically generated by SQLite
    producto.id = cursor.lastrowid
# Closes the connection when the operation finishes
    conexion.close()

    return producto

